# =============================================================================
# داشبورد زنده بازار بیت‌کوین نوبیتکس
# =============================================================================
#
# این فایل یک داشبورد وب با کتابخانه Streamlit می‌سازد.
#
# Streamlit چیست؟
# یک کتابخانه پایتون که بهت اجازه می‌ده فقط با کد پایتون
# یک اپلیکیشن وب بسازی — بدون HTML، CSS یا JavaScript!
# دقیقاً مثل Django ولی خیلی ساده‌تر، فقط برای داشبورد داده.
#
# تفاوت با Django:
#   Django → برای ساخت وب‌سایت کامل با URL، view، template، مدل
#   Streamlit → فقط برای نمایش داده و داشبورد، خیلی سریع‌تر
#
# =============================================================================

import streamlit as st   # کتابخانه اصلی داشبورد
import pandas as pd      # برای کار با جداول داده (مثل Excel در پایتون)
import psycopg2          # برای اتصال به پایگاه داده PostgreSQL
import time              # برای تاخیر زمانی (جهت رفرش خودکار)

# =============================================================================
# تنظیمات اولیه صفحه
# این باید اولین دستور Streamlit باشد
# =============================================================================
st.set_page_config(
    page_title="Nobitex Market Dashboard",  # عنوان تب مرورگر
    page_icon="📈",                          # آیکون تب مرورگر
    layout="wide",                           # استفاده از تمام عرض صفحه
)

# عنوان اصلی صفحه
st.title("📈 داشبورد زنده بازار بیت‌کوین (نوبیتکس)")
# زیرنویس توضیحی
st.caption("داده‌ها هر ۳۰ ثانیه به‌روزرسانی می‌شوند | Data refreshes every 30 seconds")


# =============================================================================
# تابع دریافت داده از پایگاه داده
# =============================================================================
#
# چرا هر بار یک اتصال جدید می‌سازیم؟
#
# در Django، معمولاً ORM مدیریت اتصال را برعهده می‌گیرد.
# اما اینجا ما مستقیم با psycopg2 کار می‌کنیم.
#
# اگر یک اتصال را ذخیره کنیم و بعد از چند دقیقه استفاده کنیم،
# PostgreSQL آن اتصال را به‌خاطر بی‌تحرکی (idle timeout) می‌بندد
# و دفعه بعد که کد سعی کند از آن استفاده کند، خطا می‌دهد!
#
# راه‌حل: هر بار که داده لازم داریم، اتصال جدید باز، داده می‌گیریم،
# و اتصال را می‌بندیم. این الگو "short-lived connection" نام دارد.
#
def fetch_data():
    """داده‌های Silver و Gold را از PostgreSQL می‌خواند."""

    # ایجاد اتصال جدید به PostgreSQL
    # این اطلاعات باید با docker-compose.yml مطابقت داشته باشد
    conn = psycopg2.connect(
        host="postgres",       # نام سرویس PostgreSQL در Docker (نه localhost!)
        database="airflow",    # نام دیتابیس
        user="airflow",        # نام کاربری
        password="airflow",    # رمز عبور
        connect_timeout=5,     # اگر در ۵ ثانیه وصل نشد، خطا بده
    )

    try:
        # ---------------------------------------------------------------
        # خواندن داده‌های Silver Layer
        # Silver Layer = داده‌های تمیز شده که Airflow هر ۵ دقیقه وارد می‌کند
        # ---------------------------------------------------------------
        silver_df = pd.read_sql(
            # این همان SQL است که در Django هم می‌نوشتیم، فقط بدون ORM
            "SELECT created_at, best_bid, best_ask, spread "
            "FROM silver_orderbook "
            "ORDER BY created_at DESC LIMIT 200",
            conn,
        )

        # ---------------------------------------------------------------
        # خواندن داده‌های Gold Layer
        # Gold Layer = آمار ساعتی تجمیع‌شده (میانگین، کمینه، بیشینه)
        # ---------------------------------------------------------------
        try:
            gold_df = pd.read_sql(
                "SELECT hour_bucket, avg_bid, avg_ask, avg_spread, "
                "min_spread, max_spread, record_count "
                "FROM gold_hourly_stats "
                "ORDER BY hour_bucket DESC LIMIT 48",
                conn,
            )
        except Exception:
            # اگر جدول Gold هنوز ساخته نشده، یک DataFrame خالی برمی‌گردانیم
            gold_df = pd.DataFrame()

    finally:
        # همیشه اتصال را ببند — حتی اگر خطا رخ داده باشد
        # در Python، finally همیشه اجرا می‌شود
        conn.close()

    return silver_df, gold_df


# =============================================================================
# دریافت داده و مدیریت خطاها
# =============================================================================
#
# در Streamlit، کد از بالا به پایین اجرا می‌شود — مثل یک اسکریپت عادی.
# هر بار که صفحه رفرش می‌شود، تمام کد دوباره اجرا می‌شود.
#
try:
    silver_df, gold_df = fetch_data()

except psycopg2.OperationalError as e:
    # این خطا وقتی رخ می‌دهد که نمی‌توان اصلاً به PostgreSQL وصل شد
    st.error(f"❌ نمی‌توان به پایگاه داده متصل شد: {e}")
    st.stop()  # اجرای بقیه کد را متوقف کن

except Exception as e:
    err = str(e)
    if "silver_orderbook" in err or "does not exist" in err:
        # این خطا وقتی رخ می‌دهد که DAG هنوز اجرا نشده و جدول ساخته نشده
        st.warning(
            "⏳ جدول داده هنوز ساخته نشده است.\n\n"
            "مطمئن شوید DAG به نام `nobitex_market_data_pipeline` "
            "در Airflow (http://localhost:8080) فعال است "
            "و حداقل یک بار اجرا شده باشد."
        )
    else:
        st.error(f"خطا: {e}")
    st.stop()


# =============================================================================
# نمایش داده‌های Silver Layer
# Silver Layer = داده‌های هر ۵ دقیقه: بهترین قیمت خرید، فروش و اسپرد
# =============================================================================

if silver_df.empty:
    # اگر داده‌ای وجود ندارد، پیام راهنما نشان بده
    st.warning("هنوز هیچ داده‌ای در دیتابیس ثبت نشده. منتظر اجرای اول DAG باشید...")

else:
    # -------------------------------------------------------------------
    # کارت‌های خلاصه (Metric Cards)
    # st.columns تقسیم‌بندی افقی صفحه است — مثل Bootstrap grid در Django
    # -------------------------------------------------------------------
    latest = silver_df.iloc[0]  # آخرین (جدیدترین) رکورد

    col1, col2, col3, col4 = st.columns(4)

    col1.metric(
        label="بهترین خریدار (تومان)",
        value=f"{latest['best_bid']:,.0f}",  # فرمت هزارتایی با کاما
    )
    col2.metric(
        label="بهترین فروشنده (تومان)",
        value=f"{latest['best_ask']:,.0f}",
    )
    col3.metric(
        label="اسپرد فعلی (تومان)",
        value=f"{latest['spread']:,.0f}",
    )
    col4.metric(
        label="تعداد رکوردهای ثبت‌شده",
        value=len(silver_df),
    )

    st.markdown("---")  # خط جداکننده افقی

    # -------------------------------------------------------------------
    # نمودار روند قیمت خرید و فروش
    # set_index → ستون created_at را محور افقی نمودار می‌کند
    # sort_index → مرتب‌سازی از قدیم به جدید برای نمایش صحیح روند
    # -------------------------------------------------------------------
    st.subheader("روند قیمت خرید و فروش")
    price_chart = (
        silver_df[['created_at', 'best_bid', 'best_ask']]
        .set_index('created_at')
        .sort_index()
    )
    st.line_chart(price_chart)

    # -------------------------------------------------------------------
    # نمودار روند اسپرد
    # اسپرد = تفاوت بین بهترین قیمت فروش و بهترین قیمت خرید
    # هرچه اسپرد کمتر باشد، بازار نقدینه‌تر (Liquid) است
    # -------------------------------------------------------------------
    st.subheader("روند اسپرد (Spread)")
    spread_chart = (
        silver_df[['created_at', 'spread']]
        .set_index('created_at')
        .sort_index()
    )
    st.line_chart(spread_chart)

    # -------------------------------------------------------------------
    # جدول داده‌های خام — در یک expander پنهان است تا صفحه شلوغ نشود
    # -------------------------------------------------------------------
    with st.expander("جدول داده‌های خام (Silver Layer)"):
        st.dataframe(silver_df, use_container_width=True)


# =============================================================================
# نمایش داده‌های Gold Layer
# Gold Layer = آمار ساعتی تجمیع‌شده برای تحلیل بلندمدت
# =============================================================================

if not gold_df.empty:
    st.markdown("---")
    st.subheader("📊 آمار ساعتی تجمیع‌شده (Gold Layer)")

    # دو ستون کنار هم برای نمایش دو نمودار
    g_col1, g_col2 = st.columns(2)

    with g_col1:
        avg_chart = (
            gold_df[['hour_bucket', 'avg_bid', 'avg_ask']]
            .set_index('hour_bucket')
            .sort_index()
        )
        st.caption("میانگین قیمت خرید و فروش به تفکیک ساعت")
        st.line_chart(avg_chart)

    with g_col2:
        spread_range_chart = (
            gold_df[['hour_bucket', 'avg_spread', 'min_spread', 'max_spread']]
            .set_index('hour_bucket')
            .sort_index()
        )
        st.caption("دامنه اسپرد (کمینه، میانگین، بیشینه) به تفکیک ساعت")
        st.line_chart(spread_range_chart)

    with st.expander("جدول داده‌های Gold Layer"):
        st.dataframe(gold_df, use_container_width=True)


# =============================================================================
# رفرش خودکار هر ۳۰ ثانیه
# =============================================================================
#
# time.sleep(30) → برنامه ۳۰ ثانیه صبر می‌کند
# st.rerun()     → بعد از ۳۰ ثانیه، تمام کد از ابتدا دوباره اجرا می‌شود
#                  این باعث می‌شود داشبورد خودکار به‌روز بشه!
#
time.sleep(30)
st.rerun()
